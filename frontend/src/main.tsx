import { StrictMode } from 'react';
import { createRoot } from 'react-dom/client';
import { BrowserRouter } from 'react-router';
import { App } from './App';
import { AuthProvider } from './auth/AuthContext';
import { applyPreferences, readPreferences, watchSystemTheme } from './preferences/preferences';
import './styles.css';

applyPreferences(readPreferences());
watchSystemTheme(() => applyPreferences(readPreferences()));

createRoot(document.getElementById('root')!).render(
  <StrictMode>
    <BrowserRouter>
      <AuthProvider>
        <App />
      </AuthProvider>
    </BrowserRouter>
  </StrictMode>,
);
